// GitHub commit adapter (REST contents API). Idempotent: committing content
// identical to what is already on the branch is a no-op.

const GITHUB_API = "https://api.github.com";

export class GitCommitError extends Error {}

interface ExistingFile {
  sha: string;
  content: string;
}

async function gh(
  token: string,
  method: string,
  path: string,
  body?: object
): Promise<Response> {
  return fetch(`${GITHUB_API}${path}`, {
    method,
    headers: {
      Authorization: `Bearer ${token}`,
      Accept: "application/vnd.github+json",
      "X-GitHub-Api-Version": "2022-11-28",
      ...(body ? { "Content-Type": "application/json" } : {}),
    },
    body: body ? JSON.stringify(body) : undefined,
  });
}

async function getExistingFile(
  token: string,
  repo: string,
  filePath: string,
  branch: string
): Promise<ExistingFile | null> {
  const res = await gh(
    token,
    "GET",
    `/repos/${repo}/contents/${encodeURIComponent(filePath).replace(/%2F/g, "/")}?ref=${encodeURIComponent(branch)}`
  );
  if (res.status === 404) return null;
  if (!res.ok) {
    throw new GitCommitError(`GitHub read failed (${res.status}) for ${repo}/${filePath}`);
  }
  const json = (await res.json()) as { sha: string; content?: string };
  const content = json.content
    ? Buffer.from(json.content, "base64").toString("utf8")
    : "";
  return { sha: json.sha, content };
}

export interface CommitResult {
  commitSha: string | null; // null when content was already up to date
  noop: boolean;
}

export async function commitFile(opts: {
  token: string;
  repo: string; // owner/repo
  workDir: string; // "" = repo root
  fileName: string;
  content: string;
  message: string;
  branch: string;
}): Promise<CommitResult> {
  const filePath = opts.workDir
    ? `${opts.workDir.replace(/\/+$/, "")}/${opts.fileName}`
    : opts.fileName;
  const existing = await getExistingFile(
    opts.token,
    opts.repo,
    filePath,
    opts.branch
  );
  if (existing && existing.content === opts.content) {
    return { commitSha: null, noop: true };
  }
  const res = await gh(
    opts.token,
    "PUT",
    `/repos/${opts.repo}/contents/${encodeURIComponent(filePath).replace(/%2F/g, "/")}`,
    {
      message: opts.message,
      content: Buffer.from(opts.content, "utf8").toString("base64"),
      branch: opts.branch,
      ...(existing ? { sha: existing.sha } : {}),
    }
  );
  if (!res.ok) {
    const text = await res.text();
    throw new GitCommitError(
      `GitHub commit failed (${res.status}) for ${opts.repo}/${filePath}: ${text.slice(0, 200)}`
    );
  }
  const json = (await res.json()) as { commit: { sha: string } };
  return { commitSha: json.commit.sha, noop: false };
}

// ---------------------------------------------------------------------------
// Repository creation
// ---------------------------------------------------------------------------

export interface EnsureRepoResult {
  repo: string;
  defaultBranch: string;
  created: boolean;
}

/** Create the destination repo if it does not exist yet. The contents API can
 * only write into a repo that already exists, so an approval flow that
 * promises "we create the infra repo" has to do this first. */
export async function ensureRepo(opts: {
  token: string;
  repo: string; // owner/name
  description?: string;
  private?: boolean;
}): Promise<EnsureRepoResult> {
  const [owner, name] = opts.repo.split("/");
  if (!owner || !name) {
    throw new GitCommitError(`repo must be "owner/name", got "${opts.repo}"`);
  }

  const existing = await gh(opts.token, "GET", `/repos/${opts.repo}`);
  if (existing.ok) {
    const json = (await existing.json()) as { default_branch: string };
    return {
      repo: opts.repo,
      defaultBranch: json.default_branch,
      created: false,
    };
  }
  if (existing.status !== 404) {
    const text = await existing.text();
    throw new GitCommitError(
      `GitHub repo lookup failed (${existing.status}) for ${opts.repo}: ${text.slice(0, 200)}`
    );
  }

  // A repo can belong to the authenticated user or to an org, and the two use
  // different endpoints. Try the org first and fall back, rather than making
  // the caller tell us which kind of owner this is.
  const body = {
    name,
    description: opts.description ?? "Infrastructure as code, generated by infralift",
    private: opts.private ?? true,
    auto_init: true, // creates the default branch so there is a ref to commit onto
  };

  let created = await gh(opts.token, "POST", `/orgs/${owner}/repos`, body);
  if (created.status === 404 || created.status === 403) {
    created = await gh(opts.token, "POST", `/user/repos`, body);
  }
  if (!created.ok) {
    const text = await created.text();
    throw new GitCommitError(
      `GitHub repo creation failed (${created.status}) for ${opts.repo}: ${text.slice(0, 200)}`
    );
  }

  const json = (await created.json()) as {
    full_name: string;
    default_branch: string;
  };
  return {
    repo: json.full_name,
    defaultBranch: json.default_branch ?? "main",
    created: true,
  };
}

// ---------------------------------------------------------------------------
// Atomic multi-file commit (git data API)
// ---------------------------------------------------------------------------

export interface CommitFilesResult {
  commitSha: string | null;
  noop: boolean;
  /** paths written, relative to the repo root */
  paths: string[];
}

/** Commit several files as one commit.
 *
 * commitFile() uses the contents API, which is one file per call and therefore
 * one commit per file. Codegen emits seven or eight files that only make sense
 * together: a reviewer landing on a commit that adds versions.tf but not the
 * resources it declares is looking at a broken tree. This walks the git data
 * API instead (blobs, tree, commit, ref) so the whole configuration arrives at
 * once, and no-ops when the resulting tree matches what the branch already has.
 */
export async function commitFiles(opts: {
  token: string;
  repo: string;
  branch: string;
  workDir: string;
  files: { fileName: string; content: string }[];
  message: string;
}): Promise<CommitFilesResult> {
  const { token, repo, branch } = opts;
  if (opts.files.length === 0) {
    return { commitSha: null, noop: true, paths: [] };
  }

  const prefix = opts.workDir ? `${opts.workDir.replace(/^\/+|\/+$/g, "")}/` : "";
  const paths = opts.files.map((f) => `${prefix}${f.fileName}`);

  // Current branch head. A repo created with auto_init always has one.
  const refRes = await gh(
    token,
    "GET",
    `/repos/${repo}/git/ref/heads/${encodeURIComponent(branch)}`
  );
  if (!refRes.ok) {
    const text = await refRes.text();
    throw new GitCommitError(
      `GitHub ref lookup failed (${refRes.status}) for ${repo}@${branch}: ${text.slice(0, 200)}`
    );
  }
  const ref = (await refRes.json()) as { object: { sha: string } };
  const headSha = ref.object.sha;

  const headCommitRes = await gh(token, "GET", `/repos/${repo}/git/commits/${headSha}`);
  if (!headCommitRes.ok) {
    throw new GitCommitError(
      `GitHub commit lookup failed (${headCommitRes.status}) for ${repo}@${headSha}`
    );
  }
  const headCommit = (await headCommitRes.json()) as { tree: { sha: string } };

  // One blob per file, then a tree layered onto the current one. Passing
  // base_tree means files outside workDir are preserved untouched.
  const tree: {
    path: string;
    mode: "100644";
    type: "blob";
    sha: string;
  }[] = [];

  for (const [i, file] of opts.files.entries()) {
    const blobRes = await gh(token, "POST", `/repos/${repo}/git/blobs`, {
      content: Buffer.from(file.content, "utf8").toString("base64"),
      encoding: "base64",
    });
    if (!blobRes.ok) {
      const text = await blobRes.text();
      throw new GitCommitError(
        `GitHub blob creation failed (${blobRes.status}) for ${paths[i]}: ${text.slice(0, 200)}`
      );
    }
    const blob = (await blobRes.json()) as { sha: string };
    tree.push({ path: paths[i], mode: "100644", type: "blob", sha: blob.sha });
  }

  const treeRes = await gh(token, "POST", `/repos/${repo}/git/trees`, {
    base_tree: headCommit.tree.sha,
    tree,
  });
  if (!treeRes.ok) {
    const text = await treeRes.text();
    throw new GitCommitError(
      `GitHub tree creation failed (${treeRes.status}) for ${repo}: ${text.slice(0, 200)}`
    );
  }
  const newTree = (await treeRes.json()) as { sha: string };

  // Identical tree means nothing changed; committing would add an empty commit.
  if (newTree.sha === headCommit.tree.sha) {
    return { commitSha: null, noop: true, paths };
  }

  const commitRes = await gh(token, "POST", `/repos/${repo}/git/commits`, {
    message: opts.message,
    tree: newTree.sha,
    parents: [headSha],
  });
  if (!commitRes.ok) {
    const text = await commitRes.text();
    throw new GitCommitError(
      `GitHub commit creation failed (${commitRes.status}) for ${repo}: ${text.slice(0, 200)}`
    );
  }
  const commit = (await commitRes.json()) as { sha: string };

  const updateRes = await gh(
    token,
    "PATCH",
    `/repos/${repo}/git/refs/heads/${encodeURIComponent(branch)}`,
    { sha: commit.sha }
  );
  if (!updateRes.ok) {
    const text = await updateRes.text();
    throw new GitCommitError(
      `GitHub ref update failed (${updateRes.status}) for ${repo}@${branch}: ${text.slice(0, 200)}`
    );
  }

  return { commitSha: commit.sha, noop: false, paths };
}
