const PROVIDER_SOURCES: Partial<
  Record<Provider, { name: string; source: string; version: string }>
> = {
  vercel: { name: "vercel", source: "vercel/vercel", version: "~> 5.0" },
  heroku: { name: "heroku", source: "heroku/heroku", version: "~> 5.0" },
  render: { name: "render", source: "render-oss/render", version: "~> 1.0" },
  digitalocean: { name: "digitalocean", source: "digitalocean/digitalocean", version: "~> 2.0" },
  firebase: { name: "google", source: "hashicorp/google", version: "~> 6.0" },
  gcp: { name: "google", source: "hashicorp/google", version: "~> 6.0" },
  aws: { name: "aws", source: "hashicorp/aws", version: "~> 5.0" },
  azure: { name: "azurerm", source: "hashicorp/azurerm", version: "~> 4.0" },
  cloudflare: { name: "cloudflare", source: "cloudflare/cloudflare", version: "~> 5.0" },
  netlify: { name: "netlify", source: "netlify/netlify", version: "~> 0.4" },
};

function renderProvider(provider: Provider): string {
  const src = PROVIDER_SOURCES[provider];
  if (!src) return `# Provider "${provider}" has no Terraform provider.\n`;

  const lines = [`provider "${src.name}" {`];

  switch (provider) {
    case "vercel":
      lines.push(`  api_token = var.vercel_api_token`);
      break;
    case "heroku":
      lines.push(`  api_key = var.heroku_api_key`);
      break;
    case "aws":
      lines.push(`  region = var.aws_region`);
      break;
    case "firebase":
    case "gcp":
      lines.push(`  project = var.gcp_project_id`);
      lines.push(`  region  = var.gcp_region`);
      break;
    case "digitalocean":
      lines.push(`  token = var.digitalocean_token`);
      break;
    case "render":
      lines.push(`  api_key  = var.render_api_key`);
      lines.push(`  owner_id = var.render_owner_id`);
      break;
    default:
      lines.push(`  # Configure credentials via environment variables`);
  }

  lines.push(`}`, ``);
  return lines.join("\n");
}

// ---------------------------------------------------------------------------
// Variables
// ---------------------------------------------------------------------------

function renderVariables(provider: Provider): string {
  const vars: Record<string, { type: string; desc: string; sensitive?: boolean; default?: string }> = {};

  switch (provider) {
    case "vercel":
      vars.vercel_api_token = { type: "string", desc: "Vercel API token", sensitive: true };
      break;
    case "heroku":
      vars.heroku_api_key = { type: "string", desc: "Heroku API key", sensitive: true };
      break;
    case "aws":
      vars.aws_region = { type: "string", desc: "AWS region", default: "us-east-1" };
      break;
    case "firebase":
    case "gcp":
      vars.gcp_project_id = { type: "string", desc: "GCP project ID" };
      vars.gcp_region = { type: "string", desc: "GCP region", default: "us-east1" };
      break;
    case "digitalocean":
      vars.digitalocean_token = { type: "string", desc: "DigitalOcean API token", sensitive: true };
      break;
    case "render":
      vars.render_api_key = { type: "string", desc: "Render API key", sensitive: true };
      vars.render_owner_id = { type: "string", desc: "Render owner/team ID" };
      // The services API returns the repo but not the branch or build command.
      vars.render_repo_url = {
        type: "string",
        desc: "Git repository for services whose repo the API did not report",
        default: "",
      };
      vars.render_branch = { type: "string", desc: "Branch to build", default: "main" };
      vars.render_build_command = {
        type: "string",
        desc: "Build command for native-runtime services",
        default: "npm ci && npm run build",
      };
      vars.render_start_command = {
        type: "string",
        desc: "Start command, required for native-runtime services",
        default: "npm start",
      };
      vars.render_image_url = {
        type: "string",
        desc: "Image URL for image-backed services",
        default: "",
      };
      break;
  }

  const lines: string[] = [];
  for (const [name, v] of Object.entries(vars)) {
    lines.push(
      `variable "${name}" {`,
      `  description = "${v.desc}"`,
      `  type        = ${v.type}`,
    );
    if (v.sensitive) lines.push(`  sensitive   = true`);
    if (v.default !== undefined) lines.push(`  default     = "${v.default}"`);
    lines.push(`}`, ``);
  }
  return lines.join("\n");
}

// ---------------------------------------------------------------------------
// Source resource generation (inventory to HCL)
// ---------------------------------------------------------------------------

function renderSourceResources(
  provider: Provider,
  inventory: ResourceInventoryItem[]
): string | null {
  const gen = SOURCE_GENERATORS[provider];
  if (!gen) return null;

  const lines: string[] = [
    `# Discovered resources from ${provider} assessment.`,
    `# Generated by infralift. Import blocks in imports.tf.`,
    ``,
  ];

  for (const item of inventory) {
    // "*:usage" items are billing line items (bandwidth, seats), not
    // infrastructure — there is nothing to declare or import.
    if (item.type.endsWith(":usage")) continue;
    const hcl = gen(item);
    if (hcl) lines.push(hcl, ``);
  }

  return lines.length > 3 ? lines.join("\n") : null;
}

// Render's API reports plans as display names ("Pro Plus"); the provider wants
// the slug ("pro_plus").
function renderPlan(plan: string | undefined, fallback = "starter"): string {
  if (!plan) return fallback;
  return plan.trim().toLowerCase().replace(/[\s-]+/g, "_");
}

// Heroku items name their app in prose ("app-name web (Basic x1)", "app-name:
// addon-service") because that is what reads well in the inventory UI. Both
// the resource generator and the import mapper need the app back out of it,
// and they must agree or the import block targets a resource that does not
// exist. Older assessments predate the connector recording appName.
function herokuApp(item: ResourceInventoryItem): {
  appName: string;
  appRef: string;
  processType: string;
} {
  const fromName = (item.name.split(" ")[0] ?? item.name).replace(/:$/, "");
  const appName = (item.metadata?.appName as string) ?? fromName;
  const processType =
    (item.metadata?.processType as string) ??
    item.externalId.split(":")[1] ??
    "web";
  return { appName, appRef: sanitizeName(appName), processType };
}

// Runtimes render_web_service accepts under runtime_source.native_runtime.
const RENDER_NATIVE_RUNTIMES = new Set([
  "elixir",
  "go",
  "node",
  "python",
  "ruby",
  "rust",
]);

function sanitizeName(name: string): string {
  return name.replace(/[^a-zA-Z0-9_]/g, "_").replace(/^[0-9]/, "_$&");
}

type ResourceGenerator = (item: ResourceInventoryItem) => string | null;

const SOURCE_GENERATORS: Partial<Record<Provider, ResourceGenerator>> = {
  vercel: (item) => {
    const name = sanitizeName(item.name);
    switch (item.type) {
      case "vercel:project": {
        const meta = item.metadata ?? {};

        // Only settings the assessment actually observed are emitted. A
        // vercel_project carrying just name and framework imports cleanly and
        // then plans "to change", because every omitted attribute reads as
        // null and the first apply wipes the project's real build_command,
        // output_directory and root_directory. Guessing a value would be
        // worse; omitting one the API did report is what caused the drift.
        const attrs: [string, unknown][] = [
          ["framework", meta.framework],
          ["build_command", meta.buildCommand],
          ["output_directory", meta.outputDirectory],
          ["root_directory", meta.rootDirectory],
          ["install_command", meta.installCommand],
          ["dev_command", meta.devCommand],
          ["node_version", meta.nodeVersion],
          ["serverless_function_region", meta.serverlessFunctionRegion],
        ];
        const present = attrs.filter(
          ([, v]) => typeof v === "string" && v.length > 0
        ) as [string, string][];

        const width = Math.max(4, ...present.map(([k]) => k.length));
        const pad = (k: string) => k.padEnd(width);

        const lines = [
          `resource "vercel_project" "${name}" {`,
          `  ${pad("name")} = ${JSON.stringify(item.name)}`,
          ...present.map(([k, v]) => `  ${pad(k)} = ${JSON.stringify(v)}`),
        ];

        const repo = meta.gitRepo as string | undefined;
        const repoType = meta.gitRepoType as string | undefined;
        if (repo && repoType) {
          const branch = meta.productionBranch as string | undefined;
          const gitPad = branch ? "production_branch".length : 4;
          lines.push(
            ``,
            `  git_repository = {`,
            `    ${"type".padEnd(gitPad)} = ${JSON.stringify(repoType)}`,
            `    ${"repo".padEnd(gitPad)} = ${JSON.stringify(repo)}`,
            ...(branch
              ? [`    production_branch = ${JSON.stringify(branch)}`]
              : []),
            `  }`
          );
        }

        lines.push(`}`);
        return lines.join("\n");
      }
      case "vercel:domain": {
        // Vercel's /v5/domains is account-scoped and does not say which
        // project a domain serves, so there is no project_id to reference.
        // Emitting one anyway produced `vercel_project.<domain-name>.id`,
        // which points at a resource that was never generated and fails
        // `validate` for every account that has a custom domain.
        const owner = item.metadata?.projectName as string | undefined;
        if (!owner) {
          return [
            `# Domain ${item.name} is registered on the account. Attach it by`,
            `# uncommenting this block and naming the project that serves it.`,
            `# resource "vercel_project_domain" "${name}" {`,
            `#   project_id = vercel_project.<project>.id`,
            `#   domain     = "${item.externalId}"`,
            `# }`,
          ].join("\n");
        }
        return [
          `resource "vercel_project_domain" "${name}" {`,
          `  project_id = vercel_project.${sanitizeName(owner)}.id`,
          `  domain     = "${item.externalId}"`,
          `}`,
        ].join("\n");
      }
      case "vercel:postgres":
        // vercel_postgres_database was removed from the provider when Vercel
        // moved managed Postgres to the Neon marketplace. There is no
        // replacement resource in vercel/vercel, so nothing here can manage
        // this store in place; it is a migration candidate, not a resource.
        return [
          `# ${item.name}: Vercel Postgres, ${item.region ?? "iad1"}.`,
          `# Vercel moved managed Postgres to the Neon marketplace and the`,
          `# provider dropped vercel_postgres_database, so this store cannot be`,
          `# expressed here. It is already priced into the migration target as`,
          `# a Neon project; move the data as part of cutover.`,
        ].join("\n");
      default:
        return `# ${item.type}: ${item.name} (no HCL mapping yet)`;
    }
  },

  heroku: (item) => {
    switch (item.type) {
      case "heroku:app": {
        const name = sanitizeName(item.name);
        return [
          `resource "heroku_app" "${name}" {`,
          `  name   = "${item.name}"`,
          `  region = "${item.region ?? "us"}"`,
          `  stack  = "${(item.metadata?.stack as string) ?? "heroku-24"}"`,
          `}`,
        ].join("\n");
      }
      case "heroku:dyno": {
        // Name is "app-name web (Basic x1)", externalId is "uuid:process_type"
        const { appRef, processType } = herokuApp(item);
        const formationName = `${appRef}_${processType}`;
        return [
          `resource "heroku_formation" "${formationName}" {`,
          `  app_id   = heroku_app.${appRef}.id`,
          `  type     = "${processType}"`,
          `  quantity = ${(item.metadata?.quantity as number) ?? 1}`,
          `  size     = "${(item.metadata?.size as string) ?? "Basic"}"`,
          `}`,
        ].join("\n");
      }
      case "heroku:addon": {
        const name = sanitizeName(item.name);
        // Name is "app-name: addon-service". herokuApp drops the trailing
        // colon before sanitizing, or the reference becomes
        // heroku_app.app_name_ and the config fails to validate.
        const { appRef } = herokuApp(item);
        return [
          `resource "heroku_addon" "${name}" {`,
          `  app_id = heroku_app.${appRef}.id`,
          `  plan   = "${(item.metadata?.plan as string) ?? item.externalId}"`,
          `}`,
        ].join("\n");
      }
      default:
        return `# ${item.type}: ${item.name} (no HCL mapping yet)`;
    }
  },

  render: (item) => {
    const name = sanitizeName(item.name);
    switch (item.type) {
      case "render:web_service": {
        // render_web_service requires a runtime_source describing where the
        // code comes from; `runtime` on its own is not an argument and every
        // Render assessment produced HCL that failed validate. The API exposes
        // the repo and the runtime but not the branch or build command, so
        // those stay variables.
        const repo = item.metadata?.repo as string | undefined;
        const repoUrl = repo ? `"${repo}"` : "var.render_repo_url";
        const runtime = ((item.metadata?.runtime as string) ?? "node").toLowerCase();

        let source: string[];
        // A native runtime has no image entrypoint, so the provider requires
        // start_command alongside it.
        let extra: string[] = [];
        if (runtime === "image") {
          source = [
            `    image = {`,
            `      image_url = var.render_image_url`,
            `    }`,
          ];
        } else if (RENDER_NATIVE_RUNTIMES.has(runtime)) {
          source = [
            `    native_runtime = {`,
            `      repo_url      = ${repoUrl}`,
            `      branch        = var.render_branch`,
            `      build_command = var.render_build_command`,
            `      runtime       = "${runtime}"`,
            `    }`,
          ];
          extra = [`  start_command = var.render_start_command`, ``];
        } else {
          // docker, or a runtime this provider version does not name natively
          source = [
            `    docker = {`,
            `      repo_url = ${repoUrl}`,
            `      branch   = var.render_branch`,
            `    }`,
          ];
        }

        return [
          `resource "render_web_service" "${name}" {`,
          `  name   = "${item.name}"`,
          `  plan   = "${renderPlan(item.metadata?.plan as string | undefined)}"`,
          `  region = "${item.region ?? "oregon"}"`,
          ``,
          ...extra,
          `  runtime_source = {`,
          ...source,
          `  }`,
          `}`,
        ].join("\n");
      }
      case "render:postgres":
        return [
          `resource "render_postgres" "${name}" {`,
          `  name    = "${item.name}"`,
          `  plan    = "${renderPlan(item.metadata?.plan as string | undefined, "free")}"`,
          `  region  = "${item.region ?? "oregon"}"`,
          `  version = "${(item.metadata?.version as string) ?? "16"}"`,
          `}`,
        ].join("\n");
      default:
        return `# ${item.type}: ${item.name} (no HCL mapping yet)`;
    }
  },

  digitalocean: (item) => {
    const name = sanitizeName(item.name);
    switch (item.type) {
      case "digitalocean:droplet":
        return [
          `resource "digitalocean_droplet" "${name}" {`,
          `  name   = "${item.name}"`,
          `  size   = "${(item.metadata?.size as string) ?? "s-1vcpu-1gb"}"`,
          `  image  = "${(item.metadata?.image as string) ?? "ubuntu-24-04-x64"}"`,
          `  region = "${item.region ?? "nyc1"}"`,
          `}`,
        ].join("\n");
      case "digitalocean:database":
        return [
          `resource "digitalocean_database_cluster" "${name}" {`,
          `  name       = "${item.name}"`,
          `  engine     = "${(item.metadata?.engine as string) ?? "pg"}"`,
          `  size       = "${(item.metadata?.size as string) ?? "db-s-1vcpu-1gb"}"`,
          `  region     = "${item.region ?? "nyc1"}"`,
          `  node_count = ${(item.metadata?.nodeCount as number) ?? 1}`,
          `}`,
        ].join("\n");
      default:
        return `# ${item.type}: ${item.name} (no HCL mapping yet)`;
    }
  },

  firebase: (item) => {
    const name = sanitizeName(item.name);
    switch (item.type) {
      // The GCP connector emits gcp:cloud_run_service; only the bare
      // gcp:cloud_run spelling was handled, so every Cloud Run service found
      // by a real GCP assessment fell through to the "no HCL mapping" comment.
      case "firebase:cloud_run":
      case "gcp:cloud_run":
      case "gcp:cloud_run_service":
        return [
          `resource "google_cloud_run_v2_service" "${name}" {`,
          `  name     = "${item.name}"`,
          `  location = "${item.region ?? "us-east1"}"`,
          ``,
          `  template {`,
          `    containers {`,
          `      image = "${(item.metadata?.image as string) ?? "gcr.io/cloudrun/hello"}"`,
          `    }`,
          `  }`,
          `}`,
        ].join("\n");
      case "firebase:cloud_sql":
      case "gcp:cloud_sql":
        return [
          `resource "google_sql_database_instance" "${name}" {`,
          `  name             = "${item.name}"`,
          `  database_version = "${(item.metadata?.version as string) ?? "POSTGRES_16"}"`,
          `  region           = "${item.region ?? "us-east1"}"`,
          ``,
          `  settings {`,
          `    tier = "${(item.metadata?.tier as string) ?? "db-f1-micro"}"`,
          `  }`,
          ``,
          `  deletion_protection = false`,
          `}`,
        ].join("\n");
      default:
        return `# ${item.type}: ${item.name} (no HCL mapping yet)`;
    }
  },
};

// ---------------------------------------------------------------------------
// Import blocks
// ---------------------------------------------------------------------------

function renderImports(
  provider: Provider,
  inventory: ResourceInventoryItem[]
): string | null {
  const mapper = IMPORT_MAPPERS[provider];
  if (!mapper) return null;

  const lines: string[] = [
    `# Import existing resources into Terraform/OpenTofu state.`,
    `# Run: terraform plan -generate-config-out=generated.tf`,
    `# Or:  tofu plan -generate-config-out=generated.tf`,
    ``,
  ];

  let count = 0;
  for (const item of inventory) {
    const imp = mapper(item);
    if (imp) {
      lines.push(
        `import {`,
        `  to = ${imp.to}`,
        `  id = "${imp.id}"`,
        `}`,
        ``,
      );
      count++;
    }
  }

  return count > 0 ? lines.join("\n") : null;
}

type ImportMapper = (item: ResourceInventoryItem) => { to: string; id: string } | null;

// Every resource the source generators emit needs a matching import block.
// Without one the resource plans as "to add" against infrastructure that
// already exists, which at best is noise in the plan and at worst creates a
// duplicate. Import ID formats are per-provider and verified against each
// provider's import documentation.
const IMPORT_MAPPERS: Partial<Record<Provider, ImportMapper>> = {
  vercel: (item) => {
    const name = sanitizeName(item.name);
    switch (item.type) {
      case "vercel:project":
        return { to: `vercel_project.${name}`, id: item.externalId };
      // vercel:domain generates a commented-out block (the domains API does
      // not report the owning project) and vercel:postgres no longer has a
      // resource at all, so neither can be imported.
      default:
        return null;
    }
  },
  heroku: (item) => {
    const name = sanitizeName(item.name);
    switch (item.type) {
      case "heroku:app":
        return { to: `heroku_app.${name}`, id: item.externalId };
      case "heroku:addon":
        return { to: `heroku_addon.${name}`, id: item.externalId };
      case "heroku:dyno": {
        // heroku_formation imports as "<app name>:<process type>", not by ID.
        // externalId is "<app uuid>:<type>", so the name is derived the same
        // way the resource generator derives it.
        const { appName, appRef, processType } = herokuApp(item);
        return {
          to: `heroku_formation.${appRef}_${processType}`,
          id: `${appName}:${processType}`,
        };
      }
      default:
        return null;
    }
  },
  render: (item) => {
    const name = sanitizeName(item.name);
    switch (item.type) {
      case "render:web_service":
        return { to: `render_web_service.${name}`, id: item.externalId };
      case "render:postgres":
        return { to: `render_postgres.${name}`, id: item.externalId };
      default:
        return null;
    }
  },
  digitalocean: (item) => {
    const name = sanitizeName(item.name);
    switch (item.type) {
      case "digitalocean:droplet":
        return { to: `digitalocean_droplet.${name}`, id: item.externalId };
      case "digitalocean:database":
        return { to: `digitalocean_database_cluster.${name}`, id: item.externalId };
      default:
        return null;
    }
  },
  firebase: gcpImportMapper,
  gcp: gcpImportMapper,
};

function gcpImportMapper(
  item: ResourceInventoryItem
): { to: string; id: string } | null {
  const name = sanitizeName(item.name);
  switch (item.type) {
    case "firebase:cloud_run":
    case "gcp:cloud_run":
    case "gcp:cloud_run_service": {
      // The Cloud Run API returns the full resource path as externalId, which
      // is already an accepted import format. Otherwise "<location>/<name>"
      // resolves against the project configured on the provider.
      const id = item.externalId.startsWith("projects/")
        ? item.externalId
        : `${item.region ?? "us-east1"}/${item.name}`;
      return { to: `google_cloud_run_v2_service.${name}`, id };
    }
    case "firebase:cloud_sql":
    case "gcp:cloud_sql":
      // The bare instance name resolves against the provider's project.
      return { to: `google_sql_database_instance.${name}`, id: item.name };
    default:
      return null;
  }
}


// ---------------------------------------------------------------------------
// Outputs
// ---------------------------------------------------------------------------

function renderOutputs(
  provider: Provider,
  inventory: ResourceInventoryItem[]
): string {
  const lines: string[] = [
    `# Generated outputs for assessed ${provider} resources.`,
    ``,
    `output "resource_count" {`,
    `  value = ${inventory.length}`,
    `}`,
    ``,
  ];

  const totalCostCents = inventory.reduce(
    (sum, i) => sum + (i.monthlyCostCents ?? 0),
    0
  );

  lines.push(
    `output "estimated_monthly_cost" {`,
    `  value = "$${(totalCostCents / 100).toFixed(2)}/mo"`,
    `}`,
    ``,
  );

  return lines.join("\n");
}

