// Assessment-to-HCL code generation.
//
// Takes ResourceInventoryItem[] from an assessment and produces Terraform/
// OpenTofu HCL that reproduces the discovered infrastructure on the source
// provider (import-ready) and optionally generates the migration target.
//
// Each provider has a mapping function that converts inventory items to HCL
// resource blocks. The output is a set of files ready to commit to a repo.

import type { ResourceInventoryItem, Provider } from "@infralift/shared";

// ---------------------------------------------------------------------------
// Public API
// ---------------------------------------------------------------------------

export interface CodegenOptions {
  /** Source provider the assessment ran against */
  provider: Provider;
  /** Discovered resources */
  inventory: ResourceInventoryItem[];
  /** Runner preference: terraform cloud, opentofu+s3, or local */
  backend: "tfc" | "s3" | "local";
  /** TFC org name (required when backend=tfc) */
  tfcOrg?: string;
  /** S3 bucket (required when backend=s3) */
  s3Bucket?: string;
  /** S3 endpoint for R2/MinIO (optional, backend=s3) */
  s3Endpoint?: string;
  /** Project name for state key namespacing */
  projectName?: string;
  /** Generate migration target alongside source */
  migrationTarget?: "cloudflare" | "hetzner" | null;
}

export interface GeneratedFile {
  fileName: string;
  content: string;
}

export function generateHcl(opts: CodegenOptions): GeneratedFile[] {
  const files: GeneratedFile[] = [];
  const project = opts.projectName ?? "infralift-migration";

  // versions.tf - required_providers + backend
  files.push({
    fileName: "versions.tf",
    content: renderVersions(opts),
  });

  // provider.tf
  files.push({
    fileName: "provider.tf",
    content: renderProvider(opts.provider),
  });

  // source.tf - discovered resources as HCL
  const sourceHcl = renderSourceResources(opts.provider, opts.inventory);
  if (sourceHcl) {
    files.push({
      fileName: `${opts.provider}.tf`,
      content: sourceHcl,
    });
  }

  // variables.tf
  files.push({
    fileName: "variables.tf",
    content: renderVariables(opts.provider),
  });

  // outputs.tf
  files.push({
    fileName: "outputs.tf",
    content: renderOutputs(opts.provider, opts.inventory),
  });

  // imports.tf - import blocks for existing resources
  const imports = renderImports(opts.provider, opts.inventory);
  if (imports) {
    files.push({ fileName: "imports.tf", content: imports });
  }

  // migration target
  if (opts.migrationTarget) {
    files.push({
      fileName: `target-${opts.migrationTarget}.tf`,
      content: renderMigrationTarget(opts.migrationTarget, opts.inventory),
    });
  }

  // README
  files.push({
    fileName: "README.md",
    content: renderReadme(opts, files),
  });

  return files;
}

// ---------------------------------------------------------------------------
// versions.tf
// ---------------------------------------------------------------------------

function renderVersions(opts: CodegenOptions): string {
  const providerSource = PROVIDER_SOURCES[opts.provider];
  const lines: string[] = [
    `# Generated by infralift. Works with Terraform >= 1.5 and OpenTofu >= 1.6.`,
    ``,
    `terraform {`,
    `  required_version = ">= 1.5"`,
    ``,
    `  required_providers {`,
  ];

  if (providerSource) {
    lines.push(
      `    ${providerSource.name} = {`,
      `      source  = "${providerSource.source}"`,
      `      version = "${providerSource.version}"`,
      `    }`,
    );
  }

  if (opts.migrationTarget === "cloudflare") {
    lines.push(
      `    cloudflare = {`,
      `      source  = "cloudflare/cloudflare"`,
      `      version = "~> 5.0"`,
      `    }`,
    );
    lines.push(
      `    neon = {`,
      `      source  = "kislerdm/neon"`,
      `      version = "~> 0.6"`,
      `    }`,
    );
  }

  lines.push(`  }`);

  // Backend
  if (opts.backend === "tfc" && opts.tfcOrg) {
    lines.push(
      ``,
      `  cloud {`,
      `    organization = "${opts.tfcOrg}"`,
      `    workspaces { name = "${opts.projectName ?? "infralift-migration"}" }`,
      `  }`,
    );
  } else if (opts.backend === "s3" && opts.s3Bucket) {
    const endpoint = opts.s3Endpoint
      ? `\n    endpoint                    = "${opts.s3Endpoint}"\n    skip_credentials_validation = true\n    skip_metadata_api_check     = true\n    skip_region_validation      = true`
      : "";
    lines.push(
      ``,
      `  backend "s3" {`,
      `    bucket = "${opts.s3Bucket}"`,
      `    key    = "${opts.projectName ?? "infralift"}/${opts.provider}/terraform.tfstate"`,
      `    region = "auto"${endpoint}`,
      `  }`,
    );
  }

  lines.push(`}`, ``);
  return lines.join("\n");
}

// ---------------------------------------------------------------------------
// Provider configs
// ---------------------------------------------------------------------------

const PROVIDER_SOURCES: Partial<
  Record<Provider, { name: string; source: string; version: string }>
> = {
  vercel: { name: "vercel", source: "vercel/vercel", version: "~> 5.0" },
  heroku: { name: "heroku", source: "heroku/heroku", version: "~> 5.0" },
  render: { name: "render", source: "render-oss/render", version: "~> 1.0" },
  digitalocean: { name: "digitalocean", source: "digitalocean/digitalocean", version: "~> 2.0" },
  firebase: { name: "google", source: "hashicorp/google", version: "~> 6.0" },
  gcp: { name: "google", source: "hashicorp/google", version: "~> 6.0" },
  aws: { name: "aws", source: "hashicorp/aws", version: "~> 5.0" },
  azure: { name: "azurerm", source: "hashicorp/azurerm", version: "~> 4.0" },
  cloudflare: { name: "cloudflare", source: "cloudflare/cloudflare", version: "~> 5.0" },
  netlify: { name: "netlify", source: "netlify/netlify", version: "~> 0.4" },
};

function renderProvider(provider: Provider): string {
  const src = PROVIDER_SOURCES[provider];
  if (!src) return `# Provider "${provider}" has no Terraform provider.\n`;

  const lines = [`provider "${src.name}" {`];

  switch (provider) {
    case "vercel":
      lines.push(`  api_token = var.vercel_api_token`);
      break;
    case "heroku":
      lines.push(`  api_key = var.heroku_api_key`);
      break;
    case "aws":
      lines.push(`  region = var.aws_region`);
      break;
    case "firebase":
    case "gcp":
      lines.push(`  project = var.gcp_project_id`);
      lines.push(`  region  = var.gcp_region`);
      break;
    case "digitalocean":
      lines.push(`  token = var.digitalocean_token`);
      break;
    case "render":
      lines.push(`  api_key  = var.render_api_key`);
      lines.push(`  owner_id = var.render_owner_id`);
      break;
    default:
      lines.push(`  # Configure credentials via environment variables`);
  }

  lines.push(`}`, ``);
  return lines.join("\n");
}

// ---------------------------------------------------------------------------
// Variables
// ---------------------------------------------------------------------------

function renderVariables(provider: Provider): string {
  const vars: Record<string, { type: string; desc: string; sensitive?: boolean; default?: string }> = {};

  switch (provider) {
    case "vercel":
      vars.vercel_api_token = { type: "string", desc: "Vercel API token", sensitive: true };
      break;
    case "heroku":
      vars.heroku_api_key = { type: "string", desc: "Heroku API key", sensitive: true };
      break;
    case "aws":
      vars.aws_region = { type: "string", desc: "AWS region", default: "us-east-1" };
      break;
    case "firebase":
    case "gcp":
      vars.gcp_project_id = { type: "string", desc: "GCP project ID" };
      vars.gcp_region = { type: "string", desc: "GCP region", default: "us-east1" };
      break;
    case "digitalocean":
      vars.digitalocean_token = { type: "string", desc: "DigitalOcean API token", sensitive: true };
      break;
    case "render":
      vars.render_api_key = { type: "string", desc: "Render API key", sensitive: true };
      vars.render_owner_id = { type: "string", desc: "Render owner/team ID" };
      break;
  }

  const lines: string[] = [];
  for (const [name, v] of Object.entries(vars)) {
    lines.push(
      `variable "${name}" {`,
      `  description = "${v.desc}"`,
      `  type        = ${v.type}`,
    );
    if (v.sensitive) lines.push(`  sensitive   = true`);
    if (v.default !== undefined) lines.push(`  default     = "${v.default}"`);
    lines.push(`}`, ``);
  }
  return lines.join("\n");
}

// ---------------------------------------------------------------------------
// Source resource generation (inventory to HCL)
// ---------------------------------------------------------------------------

function renderSourceResources(
  provider: Provider,
  inventory: ResourceInventoryItem[]
): string | null {
  const gen = SOURCE_GENERATORS[provider];
  if (!gen) return null;

  const lines: string[] = [
    `# Discovered resources from ${provider} assessment.`,
    `# Generated by infralift. Import blocks in imports.tf.`,
    ``,
  ];

  for (const item of inventory) {
    // "*:usage" items are billing line items (bandwidth, seats), not
    // infrastructure — there is nothing to declare or import.
    if (item.type.endsWith(":usage")) continue;
    const hcl = gen(item);
    if (hcl) lines.push(hcl, ``);
  }

  return lines.length > 3 ? lines.join("\n") : null;
}

function sanitizeName(name: string): string {
  return name.replace(/[^a-zA-Z0-9_]/g, "_").replace(/^[0-9]/, "_$&");
}

type ResourceGenerator = (item: ResourceInventoryItem) => string | null;

const SOURCE_GENERATORS: Partial<Record<Provider, ResourceGenerator>> = {
  vercel: (item) => {
    const name = sanitizeName(item.name);
    switch (item.type) {
      case "vercel:project":
        return [
          `resource "vercel_project" "${name}" {`,
          `  name      = "${item.name}"`,
          `  framework = "${(item.metadata?.framework as string) ?? "nextjs"}"`,
          `}`,
        ].join("\n");
      case "vercel:domain":
        return [
          `resource "vercel_project_domain" "${name}" {`,
          `  project_id = vercel_project.${sanitizeName((item.metadata?.projectName as string) ?? item.name)}.id`,
          `  domain     = "${item.externalId}"`,
          `}`,
        ].join("\n");
      case "vercel:postgres":
        return [
          `resource "vercel_postgres_database" "${name}" {`,
          `  name   = "${item.name}"`,
          `  region = "${item.region ?? "iad1"}"`,
          `}`,
        ].join("\n");
      default:
        return `# ${item.type}: ${item.name} (no HCL mapping yet)`;
    }
  },

  heroku: (item) => {
    switch (item.type) {
      case "heroku:app": {
        const name = sanitizeName(item.name);
        return [
          `resource "heroku_app" "${name}" {`,
          `  name   = "${item.name}"`,
          `  region = "${item.region ?? "us"}"`,
          `  stack  = "${(item.metadata?.stack as string) ?? "heroku-24"}"`,
          `}`,
        ].join("\n");
      }
      case "heroku:dyno": {
        // Name is "app-name web (Basic x1)", externalId is "uuid:process_type"
        const appDisplayName = item.name.split(" ")[0] ?? item.name;
        const appRef = sanitizeName(
          (item.metadata?.appName as string) ?? appDisplayName
        );
        const processType =
          (item.metadata?.processType as string) ??
          item.externalId.split(":")[1] ??
          "web";
        const formationName = `${appRef}_${processType}`;
        return [
          `resource "heroku_formation" "${formationName}" {`,
          `  app_id   = heroku_app.${appRef}.id`,
          `  type     = "${processType}"`,
          `  quantity = ${(item.metadata?.quantity as number) ?? 1}`,
          `  size     = "${(item.metadata?.size as string) ?? "Basic"}"`,
          `}`,
        ].join("\n");
      }
      case "heroku:addon": {
        const name = sanitizeName(item.name);
        // Name is "app-name: addon-service". Drop the trailing colon before
        // sanitizing, or the reference becomes heroku_app.app_name_ and the
        // config fails to validate. Assessments stored before the connector
        // recorded appName still reach this fallback.
        const appDisplayName = (item.name.split(" ")[0] ?? item.name).replace(
          /:$/,
          ""
        );
        const appRef = sanitizeName(
          (item.metadata?.appName as string) ?? appDisplayName
        );
        return [
          `resource "heroku_addon" "${name}" {`,
          `  app_id = heroku_app.${appRef}.id`,
          `  plan   = "${(item.metadata?.plan as string) ?? item.externalId}"`,
          `}`,
        ].join("\n");
      }
      default:
        return `# ${item.type}: ${item.name} (no HCL mapping yet)`;
    }
  },

  render: (item) => {
    const name = sanitizeName(item.name);
    switch (item.type) {
      case "render:web_service":
        return [
          `resource "render_web_service" "${name}" {`,
          `  name    = "${item.name}"`,
          `  plan    = "${(item.metadata?.plan as string) ?? "starter"}"`,
          `  region  = "${item.region ?? "oregon"}"`,
          `  runtime = "${(item.metadata?.runtime as string) ?? "node"}"`,
          `}`,
        ].join("\n");
      case "render:postgres":
        return [
          `resource "render_postgres" "${name}" {`,
          `  name    = "${item.name}"`,
          `  plan    = "${(item.metadata?.plan as string) ?? "free"}"`,
          `  region  = "${item.region ?? "oregon"}"`,
          `  version = "${(item.metadata?.version as string) ?? "16"}"`,
          `}`,
        ].join("\n");
      default:
        return `# ${item.type}: ${item.name} (no HCL mapping yet)`;
    }
  },

  digitalocean: (item) => {
    const name = sanitizeName(item.name);
    switch (item.type) {
      case "digitalocean:droplet":
        return [
          `resource "digitalocean_droplet" "${name}" {`,
          `  name   = "${item.name}"`,
          `  size   = "${(item.metadata?.size as string) ?? "s-1vcpu-1gb"}"`,
          `  image  = "${(item.metadata?.image as string) ?? "ubuntu-24-04-x64"}"`,
          `  region = "${item.region ?? "nyc1"}"`,
          `}`,
        ].join("\n");
      case "digitalocean:database":
        return [
          `resource "digitalocean_database_cluster" "${name}" {`,
          `  name       = "${item.name}"`,
          `  engine     = "${(item.metadata?.engine as string) ?? "pg"}"`,
          `  size       = "${(item.metadata?.size as string) ?? "db-s-1vcpu-1gb"}"`,
          `  region     = "${item.region ?? "nyc1"}"`,
          `  node_count = ${(item.metadata?.nodeCount as number) ?? 1}`,
          `}`,
        ].join("\n");
      default:
        return `# ${item.type}: ${item.name} (no HCL mapping yet)`;
    }
  },

  firebase: (item) => {
    const name = sanitizeName(item.name);
    switch (item.type) {
      case "firebase:cloud_run":
      case "gcp:cloud_run":
        return [
          `resource "google_cloud_run_v2_service" "${name}" {`,
          `  name     = "${item.name}"`,
          `  location = "${item.region ?? "us-east1"}"`,
          ``,
          `  template {`,
          `    containers {`,
          `      image = "${(item.metadata?.image as string) ?? "gcr.io/cloudrun/hello"}"`,
          `    }`,
          `  }`,
          `}`,
        ].join("\n");
      case "firebase:cloud_sql":
      case "gcp:cloud_sql":
        return [
          `resource "google_sql_database_instance" "${name}" {`,
          `  name             = "${item.name}"`,
          `  database_version = "${(item.metadata?.version as string) ?? "POSTGRES_16"}"`,
          `  region           = "${item.region ?? "us-east1"}"`,
          ``,
          `  settings {`,
          `    tier = "${(item.metadata?.tier as string) ?? "db-f1-micro"}"`,
          `  }`,
          ``,
          `  deletion_protection = false`,
          `}`,
        ].join("\n");
      default:
        return `# ${item.type}: ${item.name} (no HCL mapping yet)`;
    }
  },
};

// ---------------------------------------------------------------------------
// Import blocks
// ---------------------------------------------------------------------------

function renderImports(
  provider: Provider,
  inventory: ResourceInventoryItem[]
): string | null {
  const mapper = IMPORT_MAPPERS[provider];
  if (!mapper) return null;

  const lines: string[] = [
    `# Import existing resources into Terraform/OpenTofu state.`,
    `# Run: terraform plan -generate-config-out=generated.tf`,
    `# Or:  tofu plan -generate-config-out=generated.tf`,
    ``,
  ];

  let count = 0;
  for (const item of inventory) {
    const imp = mapper(item);
    if (imp) {
      lines.push(
        `import {`,
        `  to = ${imp.to}`,
        `  id = "${imp.id}"`,
        `}`,
        ``,
      );
      count++;
    }
  }

  return count > 0 ? lines.join("\n") : null;
}

type ImportMapper = (item: ResourceInventoryItem) => { to: string; id: string } | null;

const IMPORT_MAPPERS: Partial<Record<Provider, ImportMapper>> = {
  vercel: (item) => {
    const name = sanitizeName(item.name);
    switch (item.type) {
      case "vercel:project":
        return { to: `vercel_project.${name}`, id: item.externalId };
      default:
        return null;
    }
  },
  heroku: (item) => {
    const name = sanitizeName(item.name);
    switch (item.type) {
      case "heroku:app":
        return { to: `heroku_app.${name}`, id: item.externalId };
      case "heroku:addon":
        return { to: `heroku_addon.${name}`, id: item.externalId };
      default:
        return null;
    }
  },
  digitalocean: (item) => {
    const name = sanitizeName(item.name);
    switch (item.type) {
      case "digitalocean:droplet":
        return { to: `digitalocean_droplet.${name}`, id: item.externalId };
      case "digitalocean:database":
        return { to: `digitalocean_database_cluster.${name}`, id: item.externalId };
      default:
        return null;
    }
  },
};

// ---------------------------------------------------------------------------
// Migration target generation
// ---------------------------------------------------------------------------

function renderMigrationTarget(
  target: "cloudflare" | "hetzner",
  inventory: ResourceInventoryItem[]
): string {
  const lines: string[] = [
    `# Migration target: ${target}`,
    `# Generated by infralift based on assessed source resources.`,
    `# Review and adjust before applying.`,
    ``,
  ];

  if (target === "cloudflare") {
    // Find web services/projects to migrate to Workers
    const webResources = inventory.filter((i) =>
      ["vercel:project", "heroku:app", "render:web_service", "digitalocean:app"].includes(i.type)
    );

    for (const item of webResources) {
      const name = sanitizeName(item.name);
      lines.push(
        `# Migrated from ${item.type}: ${item.name}`,
        `# Original cost: $${((item.monthlyCostCents ?? 0) / 100).toFixed(2)}/mo`,
        `resource "cloudflare_workers_script" "${name}" {`,
        `  account_id = var.cloudflare_account_id`,
        `  name       = "${item.name}"`,
        `  content    = file("workers/${item.name}/index.js")`,
        `  module     = true`,
        `}`,
        ``,
      );
    }

    // Database resources to Neon
    const dbResources = inventory.filter((i) =>
      i.type.includes("postgres") || i.type.includes("database") || i.type.includes("sql")
    );

    if (dbResources.length > 0) {
      lines.push(
        `# Neon Postgres (replaces managed databases)`,
        `resource "neon_project" "main" {`,
        `  name      = "migrated-from-${inventory[0]?.provider ?? "source"}"`,
        `  region_id = "aws-us-east-1"`,
        `}`,
        ``,
      );
    }

    lines.push(
      `variable "cloudflare_account_id" {`,
      `  description = "Cloudflare account ID"`,
      `  type        = string`,
      `  sensitive   = true`,
      `}`,
      ``,
    );
  } else {
    // Hetzner target
    lines.push(
      `# Hetzner VPS target. Not managed by Terraform; use Docker Compose.`,
      `# Recommended: Hetzner CPX31 (~$14/mo) or CCX23 (~$25/mo)`,
      `#`,
      `# docker-compose.yml should include:`,
    );

    for (const item of inventory) {
      if (["vercel:project", "heroku:app", "render:web_service"].includes(item.type)) {
        lines.push(`#   - ${item.name} (web service)`);
      }
    }

    lines.push(
      `#   - postgres (Neon managed, or local)`,
      `#   - redis (local)`,
      `#   - caddy (reverse proxy + auto-TLS)`,
      ``,
      `# Neon database (managed Postgres, separate from VPS)`,
      `resource "neon_project" "main" {`,
      `  name      = "migrated-from-${inventory[0]?.provider ?? "source"}"`,
      `  region_id = "aws-us-east-1"`,
      `}`,
      ``,
    );
  }

  return lines.join("\n");
}

// ---------------------------------------------------------------------------
// Outputs
// ---------------------------------------------------------------------------

function renderOutputs(
  provider: Provider,
  inventory: ResourceInventoryItem[]
): string {
  const lines: string[] = [
    `# Generated outputs for assessed ${provider} resources.`,
    ``,
    `output "resource_count" {`,
    `  value = ${inventory.length}`,
    `}`,
    ``,
  ];

  const totalCostCents = inventory.reduce(
    (sum, i) => sum + (i.monthlyCostCents ?? 0),
    0
  );

  lines.push(
    `output "estimated_monthly_cost" {`,
    `  value = "$${(totalCostCents / 100).toFixed(2)}/mo"`,
    `}`,
    ``,
  );

  return lines.join("\n");
}

// ---------------------------------------------------------------------------
// README
// ---------------------------------------------------------------------------

function renderReadme(opts: CodegenOptions, files: GeneratedFile[]): string {
  const runner = opts.backend === "tfc"
    ? "Terraform Cloud"
    : opts.backend === "s3"
      ? "OpenTofu + S3 backend"
      : "local state";

  return [
    `# Infrastructure as Code`,
    ``,
    `Generated by [infralift](https://infralift.dev) from a ${opts.provider} assessment.`,
    ``,
    `## Files`,
    ``,
    ...files.filter(f => f.fileName !== "README.md").map(
      (f) => `- \`${f.fileName}\``
    ),
    ``,
    `## Usage`,
    ``,
    `\`\`\`bash`,
    `# With Terraform`,
    `terraform init`,
    `terraform plan`,
    `terraform apply`,
    ``,
    `# With OpenTofu`,
    `tofu init`,
    `tofu plan`,
    `tofu apply`,
    `\`\`\``,
    ``,
    `## Backend`,
    ``,
    `Configured for: **${runner}**`,
    ``,
    `To switch backends, edit the \`terraform {}\` block in \`versions.tf\`.`,
    ``,
    `## Import existing resources`,
    ``,
    `If you have existing infrastructure that matches these configs:`,
    ``,
    `\`\`\`bash`,
    `terraform plan    # shows what would be created`,
    `terraform import  # or use the import blocks in imports.tf`,
    `\`\`\``,
    ``,
  ].join("\n");
}
